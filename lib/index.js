/**
 * Configurable fields. Every field is `.volatile()` because the Harness
 * settings service only exposes volatile fields to a settings page, and it
 * addresses this plugin by the profile entry id declared in cordis.patch.yml.
 */
export const Config = z.object({
  /** Rewrite instruction handed to the model as the system prompt. */
  systemPrompt: z.string().default(DEFAULT_SYSTEM_PROMPT).volatile(),
  /** When true the rewrite uses the model the conversation currently has selected. */
  followSession: z.boolean().default(true).volatile(),
  /** Provider used when `followSession` is off, or as a fallback. */
  provider: z.string().default("").volatile(),
  /** Model used when `followSession` is off, or as a fallback. */
  model: z.string().default("").volatile(),
  /** Requested reasoning effort. `none` means: send no effort at all. */
  reasoningEffort: z.string().default("low").volatile(),
  /** Output ceiling for one rewrite. */
  maxOutputTokens: z.number().step(1).min(0).max(200_000).default(4096).volatile(),
  /** Wall-clock ceiling for one rewrite. */
  timeoutMs: z.number().step(1).min(1_000).max(600_000).default(60_000).volatile(),
});

export const inject = ["webServer", "llm"];

/* ------------------------------------------------------------------ helpers */

/** Raised for problems this plugin can describe to its own Client half. */
class HttpFailure extends Error {
  constructor(status, code, message) {
    super(message);
    this.name = "HttpFailure";
    this.status = status;
    this.code = code;
  }
}

/**
 * Config fields arrive as volatile references (`{ get() }`) once the loader has
 * resolved them, but a plain value is also possible. Accept both.
 */
function unwrap(value) {
  if (value !== null && typeof value === "object" && typeof value.get === "function") {
    try {
      return value.get();
    } catch {
      return undefined;
    }
  }
  return value;
}

/** Read one config field with a fallback for an absent or unusable value. */
function readField(config, key, fallback) {
  const value = unwrap(config?.[key]);
  return value === undefined || value === null ? fallback : value;
}

/** Clamp a possibly-garbage numeric config value into a usable range. */
function clampNumber(value, min, max, fallback) {
  const number = typeof value === "number" ? value : Number(value);
  if (!Number.isFinite(number)) return fallback;
  return Math.min(max, Math.max(min, Math.trunc(number)));
}

/** Write a JSON response. */
function sendJson(response, status, body) {
  const payload = JSON.stringify(body);
  response.writeHead(status, {
    "content-type": "application/json; charset=utf-8",
    "content-length": Buffer.byteLength(payload),
    "cache-control": "no-store",
  });
  response.end(payload);
}

/** Refuse a cross-origin mutating call. Non-browser callers send no Origin. */
function sameOrigin(request) {
  const origin = request.headers.origin;
  if (origin === undefined || origin === "null") return origin === undefined;
  const host = request.headers.host;
  if (host === undefined) return false;
  try {
    return new URL(origin).host === host;
  } catch {
    return false;
  }
}

/** Read and parse a bounded JSON body. */
async function readJsonBody(request) {
  const chunks = [];
  let size = 0;
  for await (const chunk of request) {
    size += chunk.length;
    if (size > MAX_BODY_BYTES) {
      throw new HttpFailure(413, "BODY_TOO_LARGE", "Request body is too large.");
    }
    chunks.push(chunk);
  }
  const raw = Buffer.concat(chunks).toString("utf8");
  if (raw.trim() === "") return {};
  try {
    const parsed = JSON.parse(raw);
    if (parsed === null || typeof parsed !== "object" || Array.isArray(parsed)) {
      throw new Error("not an object");
    }
    return parsed;
  } catch {
    throw new HttpFailure(400, "BAD_JSON", "Request body must be a JSON object.");
  }
}

/**
 * A model sometimes wraps its whole answer in one fenced block. Unwrap that
 * single outer fence, and leave any inner fences untouched.
 */
function stripOuterFence(text) {
  const match = /^\s*```[^\n]*\n([\s\S]*?)\n?```\s*$/.exec(text);
  return match === null ? text : match[1];
}

/* ------------------------------------------------------------- model routing */

/**
 * Choose the provider/model pair for this rewrite: the conversation's current
 * selection when `followSession` is on, otherwise the configured pair. Each
 * candidate is verified against the live catalog before it is used.
 */
async function resolveRoute(ctx, config, session, signal) {
  const candidates = [];
  if (readField(config, "followSession", true)) {
    const provider = typeof session?.provider === "string" ? session.provider.trim() : "";
    const model = typeof session?.model === "string" ? session.model.trim() : "";
    if (provider !== "" && model !== "") candidates.push({ provider, model, source: "session" });
  }
  const provider = String(readField(config, "provider", "")).trim();
  const model = String(readField(config, "model", "")).trim();
  if (provider !== "" && model !== "") candidates.push({ provider, model, source: "config" });

  for (const candidate of candidates) {
    try {
      await ctx.llm.resolveModelInfo(candidate.provider, candidate.model, signal);
      return candidate;
    } catch {
      // Unknown provider/model, or a catalog that is momentarily unavailable:
      // fall through to the next candidate instead of failing outright.
    }
  }
  throw new HttpFailure(
    400,
    "NO_ROUTE",
    "No usable model. Pick a model for this conversation, or name one on the plugin's settings page.",
  );
}

/**
 * Turn the configured effort id into a value the adapter will accept. An
 * unknown id is dropped rather than forwarded: `llm.stream` rejects an effort
 * the exact model does not advertise.
 */
async function resolveEffort(ctx, provider, model, desired, signal) {
  const wanted = String(desired ?? "").trim();
  if (wanted === "" || wanted === "none") return undefined;
  try {
    const info = await ctx.llm.resolveModelInfo(provider, model, signal);
    const efforts = info?.reasoning?.efforts ?? [];
    if (!efforts.some((effort) => effort.id === wanted)) return undefined;
    return ReasoningEffortId(wanted);
  } catch {
    return undefined;
  }
}

/* ---------------------------------------------------------------- rewriting */

/** Run one rewrite and return the improved text plus the route that produced it. */
async function rewriteText(ctx, config, input) {
  const { text, session, signal } = input;
  const route = await resolveRoute(ctx, config, session, signal);
  const effort = await resolveEffort(
    ctx,
    route.provider,
    route.model,
    readField(config, "reasoningEffort", "low"),
    signal,
  );

  const system = String(readField(config, "systemPrompt", DEFAULT_SYSTEM_PROMPT));
  // `0` means "no ceiling of our own". Leaving `maxTokens` off the request lets
  // whatever the provider considers the model's limit be the only limit, which
  // is what a long rewrite needs. Any other value is a real cap, and the schema
  // floor for one is a single token rather than the old 64.
  const maxTokens = clampNumber(readField(config, "maxOutputTokens", 4096), 0, 200_000, 4096);
  const messages = [
    createUserMessage({
      content: [{ type: "text", text }],
      source: { kind: "dsh-input-optimizer" },
    }),
  ];

  const options = {
    provider: route.provider,
    model: route.model,
    messages,
    signal,
    ...(maxTokens >= 1 ? { maxTokens } : {}),
    ...(system.trim() === "" ? {} : { system }),
    ...(effort === undefined ? {} : { reasoningEffort: effort }),
  };

  const assembler = new BlockAssembler();
  for await (const chunk of ctx.llm.stream(options)) {
    signal.throwIfAborted();
    assembler.push(chunk);
  }

  const finish = assembler.finish;
  if (finish?.kind === "error" || finish?.kind === "aborted") {
    const failure = finish.failure;
    const error = new Error(failure?.message ?? "The model call failed.");
    error.code = failure?.code ?? "LLM_ERROR";
    throw error;
  }
  if (finish?.kind === "max-tokens") {
    const error = new Error("The rewrite hit the output limit before it finished.");
    error.code = "MAX_TOKENS";
    throw error;
  }

  const blocks = assembler.blocks();
  const text_ = blocks
    .filter((block) => block.type === "text")
    .map((block) => block.text)
    .join("")
    .trim();

  if (text_ === "") {
    const error = new Error("The model returned an empty rewrite.");
    error.code = "EMPTY_RESPONSE";
    throw error;
  }

  return {
    text: stripOuterFence(text_),
    provider: route.provider,
    model: route.model,
    routeSource: route.source,
    reasoningEffort: effort === undefined ? null : String(effort),
    truncated: finish?.kind === "max-tokens",
  };
}

/** Map any thrown value onto a status code and a stable error code. */
function describeFailure(error, timedOut) {
  if (error instanceof HttpFailure) {
    return { status: error.status, code: error.code, message: error.message };
  }
  if (timedOut) {
    return { status: 504, code: "TIMEOUT", message: "The rewrite took too long and was cancelled." };
  }
  const code = typeof error?.code === "string" && error.code !== "" ? error.code : "INTERNAL";
  const message = error instanceof Error ? error.message : String(error);
  const status = code === "INTERNAL" ? 500 : 502;
  return { status, code: "LLM_ERROR", message, llmCode: code };
}

/* ------------------------------------------------------------------- routes */

/** POST /optimize — rewrite one draft. */
async function handleOptimize(ctx, config, request, response) {
  if (request.method !== "POST") {
    response.writeHead(405, { allow: "POST" });
    response.end();
    return;
  }
  if (!sameOrigin(request)) {
    sendJson(response, 403, { ok: false, error: { code: "CROSS_ORIGIN", message: "Cross-origin calls are refused." } });
    return;
  }

  const body = await readJsonBody(request);
  const text = typeof body.text === "string" ? body.text : "";
  if (text.trim() === "") {
    sendJson(response, 400, {
      ok: false,
      error: { code: "EMPTY_INPUT", message: "There is nothing to optimize: the input box is empty." },
    });
    return;
  }
  if (text.length > MAX_INPUT_CHARS) {
    sendJson(response, 413, {
      ok: false,
      error: { code: "INPUT_TOO_LARGE", message: `The input is longer than ${MAX_INPUT_CHARS} characters.` },
    });
    return;
  }

  // Abort the provider call when the browser goes away, and cap the total wait.
  const controller = new AbortController();
  response.on("close", () => {
    if (!response.writableEnded) controller.abort();
  });
  const timeoutMs = clampNumber(readField(config, "timeoutMs", 60_000), 1_000, 600_000, 60_000);
  const timeout = AbortSignal.timeout(timeoutMs);
  const signal = AbortSignal.any([controller.signal, timeout]);

  try {
    const result = await rewriteText(ctx, config, {
      text,
      session: body.session,
      signal,
    });
    sendJson(response, 200, { ok: true, ...result });
  } catch (error) {
    if (controller.signal.aborted) return; // the caller is gone; nobody to answer
    const failure = describeFailure(error, timeout.aborted);
    sendJson(response, failure.status, { ok: false, error: failure });
  }
}

/** GET /models — the catalog the settings page offers for a fixed model choice. */
async function handleModels(ctx, response) {
  const providers = [];
  for (const provider of ctx.llm.listProviders()) {
    let models = [];
    try {
      models = (await ctx.llm.listModels(provider.id)).map((model) => ({
        id: model.id,
        name: model.name ?? model.id,
      }));
    } catch {
      models = [];
    }
    providers.push({ id: provider.id, name: provider.name ?? provider.id, models });
  }
  sendJson(response, 200, { ok: true, providers });
}

/** GET /models/efforts — the reasoning efforts one exact model advertises. */
async function handleEfforts(ctx, url, response) {
  const provider = url.searchParams.get("provider") ?? "";
  const model = url.searchParams.get("model") ?? "";
  if (provider === "" || model === "") {
    sendJson(response, 400, {
      ok: false,
      error: { code: "MISSING_MODEL", message: "Both provider and model are required." },
    });
    return;
  }
  try {
    const info = await ctx.llm.resolveModelInfo(provider, model);
    sendJson(response, 200, {
      ok: true,
      efforts: (info.reasoning?.efforts ?? []).map((effort) => ({
        id: effort.id,
        name: effort.name ?? effort.id,
      })),
      defaultEffort: info.reasoning?.defaultEffort ?? null,
    });
  } catch (error) {
    sendJson(response, 200, {
      ok: true,
      efforts: [],
      defaultEffort: null,
      note: error instanceof Error ? error.message : String(error),
    });
  }
}

/* ------------------------------------------------------- watched file state */

/**
 * Report the state of the files a message referred to.
 *
 * The Client half cannot read file metadata at all, so "this message's files
 * were changed since it was sent" is only answerable here, where `fs` exists.
 * Each entry carries a fingerprint (size + nanosecond mtime) rather than the
 * contents: the caller compares fingerprints, so nothing is read from disk
 * beyond the directory entry itself.
 *
 * @param paths  absolute or workspace-relative paths the caller wants checked.
 * @returns one entry per requested path, in the same order.
 */
async function statPaths(paths) {
  const entries = [];
  for (const raw of paths) {
    const path = typeof raw === "string" ? raw : "";
    if (path === "" || path.length > MAX_PATH_CHARS) {
      entries.push({ path, state: "invalid" });
      continue;
    }
    try {
      // `bigint: true` yields `mtimeNs`, an exact nanosecond timestamp; the
      // float `mtimeMs` can collide for writes inside the same millisecond.
      const info = await stat(path, { bigint: true });
      if (info.isDirectory()) {
        entries.push({ path, state: "directory" });
        continue;
      }
      entries.push({
        path,
        state: "file",
        size: Number(info.size),
        fingerprint: info.mtimeNs.toString(16) + ":" + info.size.toString(16),
      });
    } catch (error) {
      const code = error?.code;
      if (code === "ENOENT" || code === "ENOTDIR") entries.push({ path, state: "missing" });
      else if (code === "EACCES" || code === "EPERM") entries.push({ path, state: "denied" });
      else entries.push({ path, state: "error", note: error instanceof Error ? error.message : String(error) });
    }
  }
  return entries;
}

/** POST /stat — fingerprint a batch of paths so the composer can gate editing. */
async function handleStat(request, response) {
  if (request.method !== "POST") {
    response.writeHead(405, { allow: "POST" });
    response.end();
    return;
  }
  if (!sameOrigin(request)) {
    throw new HttpFailure(403, "CROSS_ORIGIN", "Cross-origin calls are not accepted.");
  }
  const body = await readJsonBody(request);
  const requested = Array.isArray(body.paths) ? body.paths.slice(0, MAX_STAT_PATHS) : [];
  if (requested.length === 0) {
    sendJson(response, 200, { ok: true, entries: [], truncated: false });
    return;
  }
  const entries = await statPaths(requested);
  sendJson(response, 200, {
    ok: true,
    entries,
    truncated: Array.isArray(body.paths) && body.paths.length > MAX_STAT_PATHS,
  });
}

/* -------------------------------------------------------------------- apply */

/**
 * Mount the plugin. Every registration is owned by an effect and returns its
 * disposer, so unloading the plugin leaves nothing behind.
 */
export function apply(ctx, config) {
  // The plugin ships its own settings page, so suppress the auto-generated one.
  ctx.inject(["settings"], (child) => {
    child.effect(() => child.settings.configure({ auto: false }, ctx.fiber));
  });

  ctx.effect(() => {
    const dispose = ctx.webServer.register({
      kind: "prefix",
      path: ROUTE_PREFIX,
      handler: async (request, response) => {
        const url = new URL(request.url ?? "/", "http://dsh.internal");
        const segments = url.pathname.slice(ROUTE_PREFIX.length).split("/").filter(Boolean);
        try {
          if (segments.length === 1 && segments[0] === "optimize") {
            await handleOptimize(ctx, config, request, response);
            return;
          }
          if (segments.length === 1 && segments[0] === "stat") {
            await handleStat(request, response);
            return;
          }
          if (request.method !== "GET") {
            response.writeHead(405, { allow: "GET" });
            response.end();
            return;
          }
          if (segments.length === 1 && segments[0] === "models") {
            await handleModels(ctx, response);
            return;
          }
          if (segments.length === 2 && segments[0] === "models" && segments[1] === "efforts") {
            await handleEfforts(ctx, url, response);
            return;
          }
          sendJson(response, 404, { ok: false, error: { code: "NOT_FOUND", message: "Unknown route." } });
        } catch (error) {
          if (response.headersSent) {
            response.destroy();
            return;
          }
          const failure = describeFailure(error, false);
          sendJson(response, failure.status, { ok: false, error: failure });
        }
      },
    });
    return () => {
      dispose();
    };
  }, "input-optimizer: http routes");
}
