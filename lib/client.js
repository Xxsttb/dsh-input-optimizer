    /**
     * The composer button. Reads the live draft through the slot's `useInput`
     * hook, sends it for rewriting, and writes the result back with
     * `inputActions.setDraft`, the supported programmatic draft write.
     */
    function OptimizerButton({ useInput, inputActions, useProjection, t, disabled }) {
      const draft = useInput((state) => state.draft);
      const modelSelection = useProjection("modelSelection");
      const [busy, setBusy] = useState(false);
      const [notice, setNotice] = useState(null);

      // Read the newest draft from an event handler without re-binding it.
      const draftRef = useRef(draft);
      draftRef.current = draft;
      const abortRef = useRef(null);

      useEffect(() => {
        return () => {
          if (abortRef.current !== null) abortRef.current.abort();
        };
      }, []);

      const selection = useMemo(() => {
        if (modelSelection === undefined || modelSelection === null) return undefined;
        return modelSelection.next ?? modelSelection.lastUsed ?? undefined;
      }, [modelSelection]);

      const onClick = useCallback(
        async (event) => {
          event.preventDefault();
          if (busy) return;

          const source = typeof draftRef.current === "string" ? draftRef.current : "";
          if (source.trim() === "") {
            setNotice({ tone: "error", text: t("empty") });
            return;
          }

          const controller = new AbortController();
          abortRef.current = controller;
          setBusy(true);
          setNotice(null);
          try {
            const result = await requestRewrite(source, selection, controller.signal);
            // Never clobber text the user typed while the model was working.
            if (draftRef.current !== source) {
              setNotice({ tone: "error", text: t("edited") });
            } else if (result.text === source) {
              setNotice({ tone: "info", text: t("unchanged") });
            } else if (inputActions === undefined || typeof inputActions.setDraft !== "function") {
              setNotice({ tone: "error", text: t("failed", { message: "no input actions" }) });
            } else {
              inputActions.setDraft(result.text);
              setNotice(null);
            }
          } catch (error) {
            if (controller.signal.aborted) {
              setNotice({ tone: "info", text: t("stale") });
            } else {
              const message = error instanceof Error ? error.message : String(error);
              setNotice({ tone: "error", text: t("failed", { message }) });
            }
          } finally {
            abortRef.current = null;
            setBusy(false);
          }
        },
        [busy, inputActions, selection, t],
      );

      const blocked = disabled === true || busy;
      return h(
        React.Fragment,
        null,
        h(
          "button",
          {
            type: "button",
            className: "dsh-io-button",
            "data-busy": busy ? "true" : "false",
            "aria-label": busy ? t("busy") : t("buttonLabel"),
            title: t("buttonHint"),
            "aria-busy": busy ? "true" : undefined,
            disabled: blocked,
            // Keep the caret and selection in the editor when the button is pressed.
            onMouseDown: (event) => event.preventDefault(),
            onClick,
          },
          h(StarIcon, { size: 16 }),
        ),
        notice === null
          ? null
          : h(
              "span",
              {
                role: "status",
                className: "dsh-io-error",
                style: { position: "absolute", left: "-9999px" },
              },
              notice.text,
            ),
      );
    }

