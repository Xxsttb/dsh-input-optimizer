    function shortcutMatches(preference, event) {
      if (event.key !== "Enter") return false;
      const primary = event.ctrlKey || event.metaKey;
      if (preference === "primaryEnter") return primary && !event.shiftKey && !event.altKey;
      if (preference === "primaryShiftEnter") return primary && event.shiftKey && !event.altKey;
      if (preference === "altEnter") return event.altKey && !primary && !event.shiftKey;
      return false;
    }

    function shortcutText(preference, t) {
      if (preference === "primaryShiftEnter") return t("shortcutPrimaryShiftEnter");
      if (preference === "altEnter") return t("shortcutAltEnter");
      if (preference === "none") return t("shortcutNone");
      return t("shortcutPrimaryEnter");
    }

    /* ---- the user bubble, with a pencil ---------------------------------- */

    /** Render `@file` and `/skill` tokens as chips, without the shipped icons. */
    function renderText(text, references) {
      const nodes = [];
      const pattern = /(^|\s)(\/[\w-]+(?=\s|$)|@"[^"\n]+"|@[^\s]+)/gu;
      let cursor = 0;
      let match = pattern.exec(text);
      let index = 0;
      while (match !== null) {
        const start = match.index + match[1].length;
        const label = match[2];
        if (label.length > 1) {
          if (start > cursor) nodes.push(h("span", { key: "t" + String(index) }, text.slice(cursor, start)));
          index += 1;
          const isSlash = label.startsWith("/");
          // `@path`, `@"quoted path"` and `/skill` all name their target without
          // the sigil; only the quoted form also carries quotes.
          const target = isSlash
            ? label.slice(1)
            : label.replace(/^@/u, "").replace(/^"|"$/gu, "");
          const display = target.split(/[\\/]/u).filter(Boolean).pop() ?? label;
          const open = isSlash ? references?.openSkill : references?.openFile;
          const chip = { className: "dsh-io-chip", "data-ref-chip": isSlash ? "skill" : "file", title: label };
          nodes.push(
            typeof open === "function"
              ? h(
                  "button",
                  {
                    key: "c" + String(index),
                    type: "button",
                    className: "dsh-io-chip",
                    "data-ref-chip": isSlash ? "skill" : "file",
                    title: label,
                    onClick: (event) => {
                      if (event.detail > 1) return;
                      open(target);
                    },
                  },
                  isSlash ? label : display,
                )
              : h("span", Object.assign({ key: "c" + String(index) }, chip), isSlash ? label : display),
          );
          cursor = start + label.length;
        }
        match = pattern.exec(text);
      }
      if (cursor < text.length) nodes.push(h("span", { key: "t" + String(index) }, text.slice(cursor)));
      return nodes.length === 0 ? text : nodes;
    }

