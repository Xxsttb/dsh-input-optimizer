    /**
     * Local edit buffer over one `ConfigFormController`. The controller is the
     * source of truth; this only tracks which fields the user has touched and
     * which of them differ from what the Host currently stores. `t` is the slot
     * translator, used only to report a failed write.
     */
    function useConfigForm(form, t) {
      const snapshot = useSyncExternalStore(
        useCallback((listener) => form.subscribe(listener), [form]),
        useCallback(() => form.getSnapshot(), [form]),
      );
      const [edits, setEdits] = useState({});
      const [saving, setSaving] = useState(false);
      const [failure, setFailure] = useState(null);
      const [saved, setSaved] = useState(false);

      // Drop the edit buffer whenever the Host publishes a new revision.
      const revision = snapshot.revision;
      const lastRevision = useRef(revision);
      useEffect(() => {
        if (lastRevision.current === revision) return;
        lastRevision.current = revision;
        setEdits({});
      }, [revision]);

      const value = snapshot.value ?? {};
      const field = useCallback(
        (key) => (key in edits ? edits[key] : value[key]),
        [edits, value],
      );
      const dirty = useMemo(() => {
        return Object.keys(edits).some((key) => !Object.is(edits[key], value[key]));
      }, [edits, value]);

      const edit = useCallback((key, next) => {
        setSaved(false);
        setFailure(null);
        setEdits((current) => ({ ...current, [key]: next }));
      }, []);

      const reset = useCallback((key) => {
        setSaved(false);
        setFailure(null);
        setEdits((current) => {
          const next = { ...current };
          delete next[key];
          return next;
        });
      }, []);

      const discard = useCallback(() => {
        setEdits({});
        setFailure(null);
        setSaved(false);
      }, []);

      const save = useCallback(async () => {
        const changed = Object.keys(edits).filter((key) => !Object.is(edits[key], value[key]));
        if (changed.length === 0) return;
        setSaving(true);
        setFailure(null);
        setSaved(false);
        try {
          for (const key of changed) {
            const next = edits[key];
            // An empty text field means "restore the schema default".
            const accepted =
              next === "" || next === null || next === undefined
                ? await form.unset(key)
                : await form.set(key, next);
            if (accepted !== true) {
              setFailure(t("saveFailed"));
              return;
            }
          }
          setEdits({});
          setSaved(true);
        } catch {
          setFailure(t("saveFailed"));
        } finally {
          setSaving(false);
        }
      }, [edits, form, t, value]);

      return {
        snapshot,
        field,
        dirty,
        saving,
        failure,
        saved,
        edit,
        reset,
        discard,
        save,
      };
    }

    /** Load the provider/model catalog once, for the fixed-model pickers. */
    function useCatalog() {
      const [catalog, setCatalog] = useState({ status: "loading", providers: [] });
      useEffect(() => {
        const controller = new AbortController();
        (async () => {
          try {
            const response = await fetch(api(ROUTE_PREFIX + "/models"), {
              signal: controller.signal,
              cache: "no-store",
            });
            const payload = await readJson(response);
            if (payload !== null && payload.ok === true && Array.isArray(payload.providers)) {
              setCatalog({ status: "ready", providers: payload.providers });
            } else {
              setCatalog({ status: "failed", providers: [] });
            }
          } catch (error) {
            if (controller.signal.aborted) return;
            setCatalog({ status: "failed", providers: [] });
          }
        })();
        return () => controller.abort();
      }, []);
      return catalog;
    }

    /** Load the reasoning efforts one exact model advertises. */
    function useEfforts(provider, model) {
      const [efforts, setEfforts] = useState([]);
      useEffect(() => {
        if (typeof provider !== "string" || provider === "" || typeof model !== "string" || model === "") {
          setEfforts([]);
          return undefined;
        }
        const controller = new AbortController();
        (async () => {
          try {
            const query = new URLSearchParams({ provider, model });
            const response = await fetch(api(ROUTE_PREFIX + "/models/efforts") + "?" + query.toString(), {
              signal: controller.signal,
              cache: "no-store",
            });
            const payload = await readJson(response);
            setEfforts(payload !== null && Array.isArray(payload.efforts) ? payload.efforts : []);
          } catch {
            if (!controller.signal.aborted) setEfforts([]);
          }
        })();
        return () => controller.abort();
      }, [provider, model]);
      return efforts;
    }

