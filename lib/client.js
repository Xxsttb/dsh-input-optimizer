    /** POST one draft to the Host half and return the rewrite. */
    async function requestRewrite(text, selection, signal) {
      const response = await fetch(api(ROUTE_PREFIX + "/optimize"), {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({
          text,
          session:
            selection === undefined || selection === null
              ? null
              : { provider: selection.provider, model: selection.model },
        }),
        signal,
      });
      const payload = await readJson(response);
      if (payload === null || payload.ok !== true) {
        const message =
          payload !== null && payload.error !== undefined && typeof payload.error.message === "string"
            ? payload.error.message
            : "HTTP " + response.status;
        const error = new Error(message);
        error.code = payload !== null && payload.error !== undefined ? payload.error.code : undefined;
        throw error;
      }
      return payload;
    }

