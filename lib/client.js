    /** Split message content exactly the way the shipped bubble does. */
    function contentParts(content) {
      const texts = [];
      const attachments = [];
      const rest = [];
      for (const block of content) {
        if (block === null || typeof block !== "object") {
          rest.push(block);
        } else if (block.type === "text" && typeof block.text === "string") {
          texts.push(block.text);
        } else if (block.type === "image" && block.attachment !== undefined) {
          attachments.push({ type: "image", image: { attachment: block.attachment } });
        } else if (block.type === "file" && block.attachment !== undefined) {
          attachments.push({ type: "file", file: block.attachment });
        } else {
          rest.push(block);
        }
      }
      return { text: texts.join(""), attachments, rest };
    }

    function fileExtension(name) {
      const base = typeof name === "string" ? name : "";
      const dot = base.lastIndexOf(".");
      return dot <= 0 ? "" : base.slice(dot + 1);
    }

    function fileSizeText(bytes) {
      if (typeof bytes !== "number" || !Number.isFinite(bytes) || bytes < 0) return "";
      if (bytes < 1024) return bytes + " B";
      if (bytes < 1024 * 1024) return (bytes / 1024).toFixed(1) + " KB";
      return (bytes / (1024 * 1024)).toFixed(1) + " MB";
    }

    /**
     * The files a message referred to, as absolute paths.
     *
     * Only `@…` tokens that look like a path are taken: a token must contain a
     * separator or end in an extension, so `@someone` and a session label are
     * not mistaken for a file. `cwd` comes from the Session list.
     */
    function pathsForMessage(text, cwd) {
      const found = [];
      if (typeof text !== "string" || text === "") return { paths: found, unresolved: false };
      const pattern = /(^|\s)@("[^"\n]+"|[^\s]+)/gu;
      let match = pattern.exec(text);
      while (match !== null) {
        const raw = match[2];
        if (typeof raw === "string" && raw.length > 1) {
          const label = raw.startsWith('@"') && raw.endsWith('"') ? raw.slice(2, -1) : raw.replace(/[),.;:!?，。；：！？]+$/u, "");
          const looksLikePath = /[\\/]/u.test(label) || /\.[A-Za-z0-9]{1,8}$/u.test(label);
          if (looksLikePath && !label.endsWith("/") && !label.endsWith("\\")) found.push(label);
        }
        if (found.length >= MAX_WATCH_PATHS) break;
        match = pattern.exec(text);
      }
      const unique = [...new Set(found)];
      if (unique.length === 0) return { paths: [], unresolved: false };
      if (typeof cwd !== "string" || cwd === "") return { paths: [], unresolved: true };
      const base = cwd.endsWith("/") || cwd.endsWith("\\") ? cwd : cwd + "/";
      const paths = unique.map((label) => {
        if (/^[A-Za-z]:[\\/]/u.test(label) || label.startsWith("/") || label.startsWith("\\\\")) return label;
        return base + label;
      });
      return { paths: [...new Set(paths)], unresolved: false };
    }

    /* ---- the Harness' own fingerprint of every watched file --------------- */

    /**
     * Fingerprint the files a message mentioned, through the Harness' own
     * workspace-file service.
     *
     * `remote.workspaceFiles.stat(sessionId, path)` resolves the Session's
     * working directory on the Host and answers with an opaque `version` the
     * Host computes, so the guard needs no route of its own and inherits the
     * Session scope the service already enforces. One unresolvable answer
     * abandons the whole batch: the caller turns that into `unknown`, and the
     * guard never guesses about a file it could not read.
     */
    async function statPaths(files, sessionId, paths, signal) {
      const entries = [];
      for (const path of paths) {
        let result;
        try {
          result = await files.stat(sessionId, path, signal);
        } catch {
          return null;
        }
        if (result === null || typeof result !== "object") return null;
        if (result.ok === true) {
          const version = result.value?.version;
          entries.push({ path, state: "file", version: typeof version === "string" ? version : "" });
          continue;
        }
        const code = result.error?.code;
        if (code === "workspace-file/not-found") entries.push({ path, state: "missing" });
        else if (code === "workspace-file/not-regular-file") entries.push({ path, state: "directory" });
        else return null;
      }
      return entries;
    }

    function readJsonPreference(key) {
      if (typeof localStorage === "undefined") return null;
      try {
        const raw = localStorage.getItem(key);
        if (raw === null) return null;
        return JSON.parse(raw);
      } catch {
        return null;
      }
    }

    function writeJsonPreference(key, value) {
      if (typeof localStorage === "undefined") return;
      try {
        localStorage.setItem(key, JSON.stringify(value));
      } catch {
        /* A full or disabled store only costs persistence, never correctness. */
      }
    }

    function watchSlot(sessionId, seq) {
      return WATCH_PREFIX + String(sessionId) + ":" + String(seq);
    }

    /**
     * Whether the files this message referred to still look the same.
     *
     * DSH keeps no file history, so "changed since the message was sent" is not
     * answerable. The guard therefore records the Host's file version the first
     * time the plugin ever sees the message and blocks once a file no longer
     * matches it, is gone, or cannot be read. The limitation is documented in
     * the README.
     */
    function useFileGuard(files, paths, unresolved, sessionId, seq) {
      const key = paths.join("\n");
      const [state, setState] = useState({ status: "idle", changed: [], missing: [] });

      useEffect(() => {
        if (unresolved) {
          setState({ status: "unknown", changed: [], missing: [] });
          return undefined;
        }
        if (key === "" || !Number.isSafeInteger(seq)) {
          setState({ status: "idle", changed: [], missing: [] });
          return undefined;
        }
        // Without the workspace-file service nothing can be verified, and an
        // unverifiable file must not be presented as safe to edit.
        if (files === undefined || files === null) {
          setState({ status: "unknown", changed: [], missing: [] });
          return undefined;
        }
        const list = key.split("\n");
        const controller = new AbortController();
        let alive = true;
        const run = async () => {
          const entries = await statPaths(files, sessionId, list, controller.signal);
          if (!alive) return;
          if (entries === null) {
            setState({ status: "unknown", changed: [], missing: [] });
            return;
          }
          const baseline = readJsonPreference(watchSlot(sessionId, seq));
          const current = {};
          const changed = [];
          const missing = [];
          for (const entry of entries) {
            if (entry === null || typeof entry !== "object" || typeof entry.path !== "string") continue;
            current[entry.path] = entry.state === "file" ? entry.version : entry.state;
            if (baseline === null || typeof baseline !== "object") continue;
            if (!Object.hasOwn(baseline, entry.path)) continue;
            if (baseline[entry.path] === current[entry.path]) continue;
            if (entry.state === "missing") missing.push(entry.path);
            else changed.push(entry.path);
          }
          if (baseline === null || typeof baseline !== "object") writeJsonPreference(watchSlot(sessionId, seq), current);
          setState({
            status: changed.length > 0 ? "changed" : missing.length > 0 ? "missing" : "ready",
            changed,
            missing,
          });
        };
        setState({ status: "checking", changed: [], missing: [] });
        run().catch(() => {
          if (alive) setState({ status: "unknown", changed: [], missing: [] });
        });
        return () => {
          alive = false;
          controller.abort();
        };
      }, [files, key, unresolved, sessionId, seq]);

      return state;
    }

    /* ---- which edit of one message am I looking at ------------------------ */

    let versionRevision = 0;
    const versionListeners = new Set();

    function notifyVersions() {
      versionRevision += 1;
      for (const listener of versionListeners) listener();
    }

    function subscribeVersions(listener) {
      versionListeners.add(listener);
      return () => {
        versionListeners.delete(listener);
      };
    }

    function versionSlot(sessionId, seq) {
      return VERSION_PREFIX + String(sessionId) + ":" + String(seq);
    }

    /*
     * A branch records where its question sits *inside itself*, because the
     * answers to one question are not all at the same seq: a fork keeps the
     * numbering it was cut from, while a regenerated answer starts a fresh
     * Session and is its first question. `seq` is null for the latter, which
     * reads as "the first turn of that Session". Without this, every later
     * message of a branch would answer to the branch's version set.
     */
    function parseVersionRecord(parsed) {
      if (parsed === null || typeof parsed !== "object") return null;
      if (typeof parsed.original !== "string" || !Array.isArray(parsed.branches)) return null;
      const branches = [];
      for (const entry of parsed.branches) {
        const id = typeof entry === "string" ? entry : entry?.id;
        if (typeof id !== "string" || id === parsed.original) continue;
        if (branches.some((branch) => branch.id === id)) continue;
        const seq = typeof entry === "object" && entry !== null && Number.isSafeInteger(entry.seq) ? entry.seq : null;
        branches.push({ id, seq });
      }
      return { original: parsed.original, branches };
    }

    function readVersionRecord(sessionId, seq) {
      return parseVersionRecord(readJsonPreference(versionSlot(sessionId, seq)));
    }

    /*
     * The Session and message a version slot is anchored on. Both are already in
     * the key, which is what lets an answer whose Session shares neither lineage
     * nor numbering with its siblings still find the set it belongs to.
     */
    function versionAnchor(key) {
      if (typeof key !== "string" || !key.startsWith(VERSION_PREFIX)) return null;
      const body = key.slice(VERSION_PREFIX.length);
      const cut = body.lastIndexOf(":");
      if (cut <= 0) return null;
      const seq = Number(body.slice(cut + 1));
      if (!Number.isSafeInteger(seq)) return null;
      return { sessionId: body.slice(0, cut), seq };
    }

    /** Every key the plugin owns, which is how a Session is found by membership. */
    function storageKeys() {
      if (typeof localStorage === "undefined") return [];
      const keys = [];
      try {
        for (let index = 0; index < localStorage.length; index += 1) {
          const key = localStorage.key(index);
          if (typeof key === "string") keys.push(key);
        }
      } catch {
        /* A blocked store simply yields no keys. */
      }
      return keys;
    }

    /*
     * Which version set a Session belongs to, by membership instead of by seq.
     *
     * A branch cut before a message keeps that message's seq, so walking the
     * lineage finds its record. "Regenerate without memory" starts a Session
     * that shares neither lineage nor seq with its siblings, so the record
     * naming the Session is the only link back. The index is built on first use
     * and kept current by every write.
     */
    let versionIndex = null;

    function versionIndexOf() {
      if (versionIndex !== null) return versionIndex;
      const index = new Map();
      for (const key of storageKeys()) {
        if (!key.startsWith(VERSION_PREFIX)) continue;
        const record = parseVersionRecord(readJsonPreference(key));
        if (record === null) continue;
        for (const id of [record.original, ...record.branches.map((branch) => branch.id)]) if (!index.has(id)) index.set(id, key);
      }
      versionIndex = index;
      return index;
    }

    /**
     * Record the branch this plugin just cut, so the arrows can find it later.
     *
     * `childSeq` says where the branch point sits *inside the branch*: a fork
     * keeps the numbering of the Session it was cut from, so it is that same
     * seq, while a regenerated answer starts a fresh Session and is its first
     * question — recorded as null. Without this the arrows would answer for
     * every later message of a branch as well.
     */
    function rememberBranch(anchorSessionId, anchorSeq, childId, childSeq) {
      const record = readVersionRecord(anchorSessionId, anchorSeq) ?? { original: anchorSessionId, branches: [] };
      const point = Number.isSafeInteger(childSeq) ? childSeq : null;
      if (childId !== record.original) {
        const known = record.branches.find((branch) => branch.id === childId);
        if (known === undefined) record.branches.push({ id: childId, seq: point });
        else if (known.seq === null && point !== null) known.seq = point;
      }
      writeJsonPreference(versionSlot(anchorSessionId, anchorSeq), record);
      if (versionIndex !== null) {
        const key = versionSlot(anchorSessionId, anchorSeq);
        for (const id of [record.original, ...record.branches.map((branch) => branch.id)]) if (!versionIndex.has(id)) versionIndex.set(id, key);
      }
      notifyVersions();
    }

    /*
     * Where each answer in a version set sits *inside its own Session*.
     *
     * The original is anchored at the seq its record is stored under. A fork
     * keeps the numbering it was cut from, so its point is that same seq. A
     * regenerated answer starts a Session that holds nothing else, so its first
     * question is the point — recorded as null, which readers treat as "the
     * opening turn".
     */
    function versionPoints(record, anchorSeq) {
      const points = new Map();
      points.set(record.original, Number.isSafeInteger(anchorSeq) ? anchorSeq : null);
      for (const branch of record.branches) points.set(branch.id, branch.seq);
      return points;
    }

    /**
     * Find the version set a message belongs to, and where the current Session
     * sits in it. Returns null while a message has no recorded sibling.
     *
     * Two ways in. Walking the lineage is exact: the record is keyed by the
     * Session and the message the branch was cut from, so the walk reads that
     * one key at each hop. A regenerated answer shares neither lineage nor
     * numbering with its siblings, so the only link left is that its Session is
     * named in the record. That path serves named branches only — never the
     * Session the record is anchored on, which holds many messages of which one
     * was re-asked — and it checks the branch's own seq, so the arrows cannot
     * drift onto a later message of the same branch.
     */
    function findVersionRecord(sessions, sessionId, seq, turn) {
      if (typeof sessionId !== "string") return null;
      const byId = sessions?.byId ?? {};
      if (Number.isSafeInteger(seq)) {
        let cursor = sessionId;
        for (let hop = 0; hop < 64 && typeof cursor === "string"; hop += 1) {
          const record = readVersionRecord(cursor, seq);
          // A hit only counts when this Session is one of the versions in it.
          if (record !== null) {
            const order = [record.original, ...record.branches.map((branch) => branch.id)];
            if (order.includes(sessionId)) return { order, anchor: cursor, anchorSeq: seq, seq, points: versionPoints(record, seq) };
          }
          const parent = byId[cursor]?.parentId;
          cursor = typeof parent === "string" ? parent : undefined;
        }
      }
      const key = versionIndexOf().get(sessionId);
      if (key === undefined) return null;
      const anchor = versionAnchor(key);
      if (anchor === null) return null;
      const record = parseVersionRecord(readJsonPreference(key));
      if (record === null) return null;
      /*
       * A branch is only answerable at its own branch point. A fork keeps the
       * numbering it was cut from, so that point is a known seq. A regenerated
       * answer has no such number — its branch point is the first question of a
       * Session that was created to hold nothing else — so it is matched by turn
       * instead. Without this the arrows would appear under every later turn the
       * reader went on to have in the branch.
       */
      const branch = record.branches.find((entry) => entry.id === sessionId);
      if (branch === undefined) return null;
      const atBranchPoint = branch.seq === null ? turn === 1 : branch.seq === seq;
      if (!atBranchPoint) return null;
      return { order: [record.original, ...record.branches.map((entry) => entry.id)], anchor: anchor.sessionId, anchorSeq: anchor.seq, seq, points: versionPoints(record, anchor.seq) };
    }

    function useVersionRecord(sessions, sessionId, seq, turn) {
      useSyncExternalStore(subscribeVersions, () => versionRevision);
      const found = findVersionRecord(sessions, sessionId, seq, turn);
      if (found === null) return null;
      const index = found.order.indexOf(sessionId);
      if (index < 0) return null;
      return { order: found.order, index, anchor: found.anchor, anchorSeq: found.anchorSeq, seq: found.seq, points: found.points };
    }

    /* ---- which tools a turn used ----------------------------------------- */

    /**
     * Every tool name a tool-call projection mentions.
     *
     * A running call carries `name`; a finished one carries it under `call`.
     * A call that started before the plugin saw it has neither yet, which is
     * why an unnamed entry counts as unknown and blocks editing below.
     */
    function collectToolNames(root, out) {
      if (root === null || typeof root !== "object") return out;
      // A running call is the call; a finished one nests it under `call`.
      const call = root.call !== null && typeof root.call === "object" && typeof root.call.name === "string" && root.call.name !== "" ? root.call : root;
      // An empty name means the call started before this renderer saw it, so it
      // is reported as unknown rather than silently treated as harmless.
      out.add(typeof call.name === "string" ? call.name : "");
      if (Array.isArray(root.subCalls)) for (const child of root.subCalls) collectToolNames(child, out);
      return out;
    }

    /**
     * How many tool calls in a turn have no name recorded yet.
     *
     * Kept separate from the joined name list because a turn whose only call is
     * unnamed would otherwise join to the empty string, which reads as "this
     * turn used no tools" — the opposite of what an unknown call means.
     */
    function selectUnnamedTools(snapshot, turn) {
      if (turn === undefined) return 0;
      let unnamed = 0;
      for (const key of snapshot.locations.getTurn(turn)) {
        const candidate = snapshot.nodes.get(key);
        if (candidate === undefined || candidate.kind !== "tool-call") continue;
        for (const name of collectToolNames(candidate.data?.root, new Set())) if (name === "") unnamed += 1;
      }
      return unnamed;
    }

    /** The tools one turn used, joined for a value-stable selector result. */
    function selectTurnTools(snapshot, turn) {
      if (turn === undefined) return "";
      const names = new Set();
      for (const key of snapshot.locations.getTurn(turn)) {
        const candidate = snapshot.nodes.get(key);
        if (candidate === undefined || candidate.kind !== "tool-call") continue;
        collectToolNames(candidate.data?.root, names);
      }
      names.delete("");
      return [...names].sort().join(", ");
    }

    /** The prompt that opened one turn, as the human node records it. */
    function turnUser(snapshot, turn) {
      if (turn === undefined || turn < 0) return undefined;
      let steering;
      for (const key of snapshot.locations.getTurn(turn)) {
        const candidate = snapshot.nodes.get(key);
        if (candidate === undefined) continue;
        if (candidate.kind !== "user" && candidate.kind !== "steering") continue;
        if (typeof candidate.data?.seq !== "number") continue;
        const parts = contentParts(Array.isArray(candidate.data.content) ? candidate.data.content : []);
        const found = { seq: candidate.data.seq, text: parts.text };
        if (candidate.kind === "user") return found;
        steering ??= found;
      }
      return steering;
    }

    function turnOfNode(node) {
      const location = node?.location;
      if (location === undefined) return undefined;
      if (location.kind !== "turn" && location.kind !== "step") return undefined;
      return location.turn.turn;
    }

    /**
     * The turn whose tail carries the given assistant message.
     *
     * This is the reverse of what the shipped branch button does: it walks from
     * a seq to a message id, while an action strip sitting under an answer only
     * knows the message id it was handed.
     */
    function turnOfMessage(snapshot, messageId) {
      if (typeof messageId !== "string") return undefined;
      for (const [turn, group] of snapshot.timeline.turns) {
        if (group?.data?.get("turn-tail")?.closing?.finalNode?.messageId === messageId) return turn;
      }
      return undefined;
    }

    /**
     * Everything the guard needs about the turn a message opens or closes.
     *
     * `busy` covers a turn the model is still answering: editing it would race
     * with the answer already being written. `tools` is the raw joined names,
     * and `blocked` is the whitelist decision, computed here so both the pencil
     * and the regenerate button agree on it.
     */
    function useTurnFacts(useChat, turn) {
      const tools = useChat((snapshot) => selectTurnTools(snapshot, turn));
      const unnamed = useChat((snapshot) => selectUnnamedTools(snapshot, turn));
      const busy = useChat((snapshot) => {
        const group = snapshot.timeline.turns.get(turn);
        return group === undefined ? false : group.status !== "closed";
      });
      // Both selectors return primitives: `turnUser` builds a fresh object on
      // every call, and an identity-compared selector would never settle.
      const prompt = useChat((snapshot) => turnUser(snapshot, turn)?.text ?? "");
      const seq = useChat((snapshot) => turnUser(snapshot, turn)?.seq ?? -1);
      const named = tools === "" ? [] : tools.split(", ");
      const foreign = named.filter((name) => !READ_ONLY_TOOLS.has(name));
      const unknown = unnamed > 0;
      return {
        tools: named,
        blocked: unknown || foreign.length > 0,
        foreign: unknown ? [...foreign, ""] : foreign,
        busy,
        prompt,
        seq: seq >= 0 ? seq : undefined,
        /*
         * Which turn this is inside its Session, 1-based — `turn/start` already
         * numbers turns from one. A regenerated answer is the first question of
         * a Session that holds nothing else, and that ordinal is the only thing
         * that tells its branch point apart from the turns the reader has since
         * added to the same branch.
         */
        turnNumber: typeof turn === "number" ? turn : undefined,
      };
    }

